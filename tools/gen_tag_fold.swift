// Regenerates src/tag_fold.rs: single-character Traditional -> Simplified pairs
// from the system ICU "Hant-Hans" transform, used only to match duplicate tags.
// Run on macOS: swift tools/gen_tag_fold.swift > src/tag_fold.rs
import Foundation

let ranges: [ClosedRange<UInt32>] = [0x3400...0x4DBF, 0x4E00...0x9FFF, 0xF900...0xFAFF]
var pairs: [(UInt32, UInt32)] = []
for range in ranges {
    for code in range {
        guard let scalar = Unicode.Scalar(code) else { continue }
        let source = String(Character(scalar))
        guard let target = source.applyingTransform(StringTransform("Hant-Hans"), reverse: false),
              target != source, target.unicodeScalars.count == 1,
              let mapped = target.unicodeScalars.first else { continue }
        pairs.append((code, mapped.value))
    }
}
print("// @generated by tools/gen_tag_fold.swift from the ICU Hant-Hans transform; do not edit.")
print("/// Sorted (traditional, simplified) pairs for `tag_key`.")
print("pub static TRAD_TO_SIMP: &[(char, char)] = &[")
for (from, to) in pairs {
    print(String(format: "    ('\\u{%X}', '\\u{%X}'),", from, to))
}
print("];")
